"""Build the nl_tower data from code and seeds (CPU only), or check a built tree against the published artifacts.

    python -m nl_tower.prepare_data [--workdir DIR] STAGE [STAGE ...]

Stages, in dependency order:
  tests     the 1,024-question test sets and question pools in data/<spec>/corpus_tw1/
  rl-pools  the RL prompt pools results/rl_prompts/<spec>.jsonl
  mixes     the Base and Extended RL prompt JSONs in unified_data/ (needs tests and rl-pools)
  corpus    the 510M-token midtraining corpus data/nltw_m/corpus_tw1X/cot.jsonl: exclusion list, question pools drawn
            with it, solver traces, shuffled mix and its contamination audit (needs tests and rl-pools; ~4 GB)
  demos     unified_data/demos_tw1X.jsonl and the anchor round unified_data/anchors/demos_tw1X_resp/ that
            UNIFIED_ANCHOR_DIRS points at (needs corpus, --tokenizer and the trainer package)
  verify    compare the files with artifacts.json (exit 1 on any difference)

Seeds, sizes and exclusions come from data_spec.json; outputs go under --workdir (default NL_TOWER_WORKDIR, else
$DATA_DIR/nl_tower). Existing outputs are kept and never overwritten, so an interrupted run resumes when started again.
Items are generated by RG_WORKERS forked workers (default: the available CPUs, at most 32; identical to sequential
generation).
The pretraining rows of the pre+mid+RL runs (Appendix C.8) are built by ``unified_training.tools.build_pretrain_rows``
(experiments/controlled/data.sh).
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

from . import demos, manifest, mixes, paths, pools, traces
from .specs import rg_workers

HERE = Path(__file__).resolve().parent
SPEC = HERE / "data_spec.json"
RECORD = HERE / "artifacts.json"
BUILT_GROUPS = ("tests", "pools", "rl_pools", "corpus", "mixes", "demos")


def log(msg: str) -> None:
    print(f"[nl_tower data {time.strftime('%Y-%m-%d %H:%M:%S')}] {msg}", flush=True)


def _need(path: Path) -> bool:
    if path.exists():
        log(f"exists, kept: {path}")
        return False
    return True


def _expect(rows: list, n: int, what: str) -> list:
    if len(rows) != n:
        raise SystemExit(f"ERROR: {what}: {len(rows)} rows, expected {n} (generator stream exhausted?)")
    return rows


def stage_tests(root: Path, spec: dict, only: set[str] | None = None) -> None:
    for qs in spec["question_sets"]:
        if only and qs["spec"] not in only:
            continue
        out = root / qs["dir"]
        files = [(out / "test.jsonl", qs["n_test"]), (out / "pool.jsonl", qs["n_pool"])]
        missing = [(p, n) for p, n in files if n and _need(p)]
        if not missing:
            continue
        exclude = pools.read_qids(root / e for e in qs["exclude"])
        test, pool, n_excl = pools.pool_rows(qs["spec"], qs["n_pool"], qs["n_test"], qs["seed"], exclude, log)
        rows = {out / "test.jsonl": _expect(test, qs["n_test"], f"{qs['spec']} test"),
                out / "pool.jsonl": _expect(pool, qs["n_pool"], f"{qs['spec']} pool")}  # fmt: skip
        for p, _ in missing:
            pools.write_jsonl(p, rows[p])
        log(json.dumps({"spec": qs["spec"], "seed": qs["seed"], "test": len(test), "pool": len(pool),
                        "excluded": n_excl, "n_exclude_qids": len(exclude)}))  # fmt: skip


def stage_rl_pools(root: Path, spec: dict) -> None:
    for rp in spec["rl_pools"]:
        out = root / rp["file"]
        if _need(out):
            rows = _expect(pools.rl_pool_rows(rp["spec"], rp["n"], rp["seed"]), rp["n"], rp["file"])
            pools.write_jsonl(out, rows)
            log(json.dumps({"spec": rp["spec"], "rl_prompts": len(rows), "seed": rp["seed"], "path": rp["file"]}))


def stage_mixes(root: Path, spec: dict) -> None:
    levels = mixes.build_levels(root, spec)
    for rel, rows in levels["files"].items():
        if _need(root / rel):
            mixes.write_json(root / rel, rows, ensure_ascii=levels["ensure_ascii"][rel])
            log(f"wrote {rel}: {len(rows)} prompts")
    log(json.dumps({"train_prompts": levels["sizes"]}))


def _concat(parts: list[Path], out: Path) -> None:
    with open(str(out) + ".tmp", "wb") as dst:
        for p in parts:
            with open(p, "rb") as src:
                shutil.copyfileobj(src, dst)
    os.replace(str(out) + ".tmp", out)


def stage_corpus(root: Path, spec: dict) -> None:
    c = spec["corpus"]
    data = paths.get("data", root)
    excl_path = root / c["exclusion_list"]
    if _need(excl_path):
        rows = pools.exclusion_rows(root, mixes.verl_prompt_tables(root, spec))
        pools.write_jsonl(excl_path, rows)
        log(json.dumps({"exclude_rows": len(rows), "unique_qids": len({r["qid"] for r in rows})}))
    exclude = pools.read_qids([excl_path])
    for qp in c["question_pools"]:
        out = data / qp["spec"] / f"corpus_{qp['part']}" / "pool.jsonl"
        if _need(out):
            _, rows, n_excl = pools.pool_rows(qp["spec"], qp["n"], 0, qp["seed"], exclude, log)
            pools.write_jsonl(out, _expect(rows, qp["n"], f"{qp['spec']} {qp['part']} pool"))
            log(json.dumps({"spec": qp["spec"], "part": qp["part"], "seed": qp["seed"], "pool": len(rows),
                            "excluded": n_excl}))  # fmt: skip
    tag, k, trace_seed = c["tag"], c["traces"]["k"], c["traces"]["seed"]
    for rung in c["rungs"]:  # the corpus's question pool per rung: its parts in spec order
        out = data / rung / f"corpus_{tag}" / "pool.jsonl"
        if _need(out):
            parts = [
                data / rung / f"corpus_{qp['part']}" / "pool.jsonl" for qp in c["question_pools"] if qp["spec"] == rung
            ]
            out.parent.mkdir(parents=True, exist_ok=True)
            _concat(parts, out)
    audit_excl = root / c["audit_exclusion_list"]
    if _need(audit_excl):
        audit_excl.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(excl_path, str(audit_excl) + ".tmp")
        os.replace(str(audit_excl) + ".tmp", audit_excl)
    cot = {rung: data / rung / f"corpus_{tag}" / f"cot_k{k}.jsonl" for rung in c["rungs"]}
    for rung, out in cot.items():
        if _need(out):
            rows, summary = traces.cot_rows(
                pools.read_jsonl(data / rung / f"corpus_{tag}" / "pool.jsonl"), k, 0, trace_seed
            )
            pools.write_jsonl(out, rows)
            log(json.dumps({"spec": rung, **summary}))
    corpus = root / c["corpus"]
    if _need(corpus):
        rows = pools.mix_rows([pools.read_jsonl(cot[rung]) for rung in c["rungs"]], c["mix_seed"])
        pools.write_jsonl(corpus, rows)
        log(json.dumps({"corpus": c["corpus"], "rows": len(rows)}))
    audit_path = root / c["audit"]
    if _need(audit_path):
        report = pools.audit(corpus, pools.read_jsonl(audit_excl), root)
        with open(str(audit_path) + ".tmp", "w") as f:
            json.dump(report, f, indent=1)
        os.replace(str(audit_path) + ".tmp", audit_path)
        log(json.dumps(report["new"]))
        if report["new"]["total_overlap"]:
            raise SystemExit(f"ERROR: the corpus overlaps the exclusion list: {report['new']}")


def stage_demos(root: Path, spec: dict, tokenizer: str | None) -> None:
    """Demo JSONL (corpus order) and the response-masked anchor round, built by the trainer's anchor builder."""
    tag = spec["corpus"]["tag"]
    ud = paths.get("unified_data", root)
    jsonl = ud / f"demos_{tag}.jsonl"
    if _need(jsonl):
        n = demos.write_demo_jsonl(root / spec["corpus"]["corpus"], jsonl)
        log(f"demos {tag}: {n} rows -> {jsonl}")
    out = ud / "anchors" / f"demos_{tag}_resp"
    if (out / "DONE").exists():
        log(f"exists, kept: {out}")
        return
    if not tokenizer:
        raise SystemExit("ERROR: the demos stage needs --tokenizer (any 124M checkpoint: GPT-2 BPE, EOS 50256)")
    env = dict(os.environ, ANCHOR_JSONL=str(jsonl), ANCHOR_OUT=str(out), ANCHOR_TOKENIZER=tokenizer,
               ANCHOR_MASK="response", ANCHOR_MAX_PROMPT="640", ANCHOR_MAX_RESPONSE="1280", ANCHOR_WEIGHT="1.0")  # fmt: skip
    subprocess.run([sys.executable, "-m", demos.ANCHOR_BUILDER], env=env, check=True)


def stage_verify(root: Path, record_path: Path, groups: list[str] | None, strict: bool) -> None:
    record = json.loads(record_path.read_text())
    results = manifest.check(record, root, groups or list(BUILT_GROUPS))
    counts: dict[str, int] = {}
    for status, group, rel, detail in results:
        counts[status] = counts.get(status, 0) + 1
        print(f"{status} {group} {rel} ({detail})", flush=True)
    print(json.dumps(counts), flush=True)
    if counts.get("DIFF") or (strict and counts.get("MISSING")):
        raise SystemExit(1)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("stages", nargs="+", choices=["tests", "rl-pools", "mixes", "corpus", "demos", "verify"])
    ap.add_argument("--workdir", default=None, help="output root (default: NL_TOWER_WORKDIR, else $DATA_DIR/nl_tower)")
    ap.add_argument("--spec", default=str(SPEC), help="data spec (default: data_spec.json of this package)")
    ap.add_argument("--record", default=str(RECORD), help="verify: recorded artifacts (default: artifacts.json)")
    ap.add_argument("--only", nargs="*", default=None, help="tests: build only these specs (e.g. nltw_e nltw_hb12)")
    ap.add_argument("--tokenizer", default=os.environ.get("NL_TOWER_TOKENIZER"), help="demos: HF tokenizer dir")
    ap.add_argument("--groups", nargs="*", default=None, help=f"verify: groups (default {' '.join(BUILT_GROUPS)})")
    ap.add_argument("--strict", action="store_true", help="verify: a missing file is an error too")
    a = ap.parse_args()
    root = Path(a.workdir) if a.workdir else paths.workdir()
    spec = json.loads(Path(a.spec).read_text())["data"]
    log(f"workdir {root}; RG_WORKERS={rg_workers()}; stages {' '.join(a.stages)}")
    for stage in a.stages:
        t0 = time.time()
        if stage == "tests":
            stage_tests(root, spec, set(a.only) if a.only else None)
        elif stage == "rl-pools":
            stage_rl_pools(root, spec)
        elif stage == "mixes":
            stage_mixes(root, spec)
        elif stage == "corpus":
            stage_corpus(root, spec)
        elif stage == "demos":
            stage_demos(root, spec, a.tokenizer)
        else:
            stage_verify(root, Path(a.record), a.groups, a.strict)
        log(f"stage {stage} done in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
