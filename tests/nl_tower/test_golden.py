@pytest.mark.parametrize(
    "spec,seed,size,want",
    [s[1:] for s in STREAMS],
    ids=[f"{s[1]}-seed{s[2]}-{s[0].rsplit('/', 1)[1].split('.')[0]}" for s in STREAMS],
)
def test_first_questions(spec, seed, size, want):
    ds = make_dataset(spec, size=size, seed=seed)
    got, seen = [], set()
    for i in range(len(want) + 3):
        h = qhash(ds[i]["question"])
        if h not in seen:
            seen.add(h)
            got.append(h)
        if len(got) == len(want):
            break
    assert got == want


@pytest.mark.parametrize("item", FIXTURE["items"], ids=[str(it["corpus_row"]) for it in FIXTURE["items"]])
def test_corpus_traces(item):
    """The trace of a tw1X corpus row is one of the K = 4 traces the solver writes for its question."""
    made = question_traces(item["pool_row"], k=4)
    assert item["target_sha256"] in {hashlib.sha256(t.encode()).hexdigest() for t in made}


# tw1X questions: the first 40,000 per rung come from the tw1L streams, the other 60,000 from the tw1Xnew streams.
CORPUS_SEEDS = {"nltw_e": (31000000, 33000000), "nltw_m0": (32000000, 34000000)}


@pytest.mark.parametrize("item", FIXTURE["items"][:2], ids=[str(it["corpus_row"]) for it in FIXTURE["items"][:2]])
def test_corpus_question_reproduced(item):
    """A stored corpus question record is regenerated byte for byte from its rung, seed and stream index."""
    r = item["pool_row"]
    idx = r["metadata"]["source_index"]
    for seed in CORPUS_SEEDS[item["spec"]]:
        e = make_dataset(item["spec"], size=idx + 1, seed=seed)[idx]
        if qhash(e["question"]) == r["qid"]:
            row = {
                "qid": r["qid"],
                "prompt": e["question"] + "\n\nAnswer: ",
                "question": e["question"],
                "answer": str(e["answer"]),
                "metadata": e["metadata"],
            }
            assert json.dumps(row) == json.dumps(r)
            return
    pytest.fail(f"question {r['qid']} not found at index {idx} of the corpus streams")
